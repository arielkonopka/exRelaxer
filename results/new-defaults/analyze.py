# nl grids: best validation-chosen test error / accuracy per (task, model)
def nl_best(name):
    """Per (task, model): the (depth, width, lr) with the best median validation score, and its median test score.
    Binary tasks score accuracy (higher is better), the others MSE."""
    by = defaultdict(list)
    for t in trials(name):
        p = t["params"]
        task = p["task"] + (f" k={p['k']}" if p["task"] == "l4" else "") + (f" n={p['n']}" if p["task"] == "t3" else "")
        by[(task, p["model"], (p["depth"], p["width"], p["lr"]))].append(t["metrics"])
    best = {}
    for (task, model, cfg), ms in by.items():
        binary = task[0] == "t" and not task.startswith("t4")
        vkey = "best_validation" if task[0] == "t" else "best_validation_mse"
        tkey = "test_accuracy" if binary else "test_mse"
        vals = [m[vkey] for m in ms if m.get(vkey) is not None]
        tests = [m[tkey] for m in ms if m.get(tkey) is not None]
        if not vals or not tests:
            continue
        val, test = statistics.median(vals), statistics.median(tests)
        k = (task, model)
        if k not in best or (val > best[k][0] if binary else val < best[k][0]):
            best[k] = (val, test, cfg)
    return best


def diverged(name, models=("er", "gate", "clamp")):
    out = defaultdict(lambda: [0, 0])
    for t in trials(name):
        p = t["params"]
        if p["model"] in models:
            mse = t["metrics"].get("test_mse")
            if mse is not None:
                o = out[(p["model"], p["lr"])]
                o[0] += mse > 1
                o[1] += 1
    return out


