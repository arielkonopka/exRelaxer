    print(f"## {exp}: best configuration per task and model\n")
    print("Test score (median over 5 trials) of the configuration (depth, width, lr) with the best median "
          "validation score: MSE on l0-l4 and t4 (lower is better), accuracy on t1-t3.\n")
    print("| task | model | " + " | ".join(NL_L) + " |")
    print("|---" * (len(NL_L) + 2) + "|")
    bests = {v: {} for v in NL_V}
    for g in groups:
        for v in NL_V:
            bests[v].update(nl_best(f"{exp}_{g}_{v}"))
    for k in sorted(bests["old"]):
        cells = []
        for v in NL_V:
            b = bests[v].get(k)
            cells.append("–" if b is None else f"{b[1]:.3g}")
        print(f"| {k[0]} | {k[1]} | " + " | ".join(cells) + " |")
    print()
    if exp == "nl_static":
        print("Runs diverging (test MSE > 1), all static tasks, by learning rate:\n")
        print("| model | lr | " + " | ".join(NL_L) + " |")
        print("|---" * (len(NL_L) + 2) + "|")
        agg = {v: defaultdict(lambda: [0, 0]) for v in NL_V}
        for v in NL_V:
            for g in groups:
                for k, (d, n) in diverged(f"{exp}_{g}_{v}").items():
                    agg[v][k][0] += d
                    agg[v][k][1] += n
        for k in sorted(agg["old"]):
            print(f"| {k[0]} | {k[1]} | " + " | ".join(
                f"{100 * agg[v][k][0] / agg[v][k][1]:.0f} %" if agg[v][k][1] else "–" for v in NL_V) + " |")
        print()

