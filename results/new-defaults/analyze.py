"""Tables for results/new-defaults/summary.md from the output of run.sh and run_python.sh.

Usage: python3 results/new-defaults/analyze.py RAW_DIR > results/new-defaults/summary.md
RAW_DIR holds NAME.jsonl or NAME.jsonl.gz files named EXPERIMENT_VARIANT."""
import gzip, json, os, statistics, sys
from collections import defaultdict

RAW = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "raw")


def lines(name):
    for ext in (".jsonl", ".jsonl.gz"):
        f = os.path.join(RAW, name + ext)
        if os.path.exists(f):
            with (gzip.open(f, "rt") if ext.endswith("gz") else open(f)) as fh:
                for l in fh:
                    yield json.loads(l)
            return


def trials(name):
    return [d for d in lines(name) if d["type"] == "trial" and not d.get("error")]


def mean(name, metric):
    v = [t["metrics"][metric] for t in trials(name) if t["metrics"].get(metric) is not None]
    if not v:
        return None
    se = statistics.stdev(v) / len(v) ** 0.5 if len(v) > 1 else 0.0
    return statistics.fmean(v), se


def fmt(x):
    if x is None:
        return "–"
    m, se = x
    return f"{m:.3g} ± {se:.2g}" if se else f"{m:.3g}"


def table(exp, variants, metrics, labels):
    print("| metric | " + " | ".join(labels) + " |")
    print("|---" * (len(labels) + 1) + "|")
    for m in metrics:
        print(f"| {m} | " + " | ".join(fmt(mean(f"{exp}_{v}", m)) for v in variants) + " |")
    print()


